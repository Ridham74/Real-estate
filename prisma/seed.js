async function main() {
  console.log("Seeding demonstration properties into SQLite database...");

  // Upsert all demonstration properties
  for (const property of demoProperties) {
    await prisma.property.upsert({
      where: { id: property.id },
      update: property,
      create: property,
    });
  }

  const count = await prisma.property.count();
  console.log(`Database seeding completed successfully. Total properties in database: ${count}`);
}

main()
  .catch((e) => {
    console.error("Seeding error:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
